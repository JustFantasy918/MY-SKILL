/**
 * 获取城市经度（精确匹配）
 */
function getCityLongitude(province, city) {
  var p = CITY_DATA[province];
  if (!p) return null;
  if (city && p[city] !== undefined) return p[city];
  // 取该省省会/第一个城市
  var firstCity = Object.keys(p)[0];
  return p[firstCity];
}

/**
 * 列出所有省份
 */
function listProvinces() {
  return Object.keys(CITY_DATA);
}

/**
 * 列出某省所有城市
 */
function listCities(province) {
  var p = CITY_DATA[province];
  if (!p) return [];
  return Object.keys(p);
}

/**
 * 模糊搜索城市（支持自由输入）
 * 输入任意城市名（含"市""区""县"后缀），返回匹配结果
 * @param {string} keyword - 城市名关键词，如"苏州""苏州市""昆山""深圳市南山区"
 * @returns {array} 匹配结果 [{province, city, longitude, score}]
 */
function searchCity(keyword) {
  if (!keyword) return [];
  // 去除常见后缀
  var clean = keyword.replace(/[市区县旗州]/g, '').trim();
  var results = [];

  for (var prov in CITY_DATA) {
    for (var city in CITY_DATA[prov]) {
      var score = 0;
      // 精确匹配
      if (city === keyword) score = 100;
      // 去后缀后精确匹配
      else if (city === clean) score = 95;
      // 包含匹配
      else if (city.indexOf(clean) >= 0 || clean.indexOf(city) >= 0) score = 80;
      // 模糊匹配（至少2字重合）
      else if (clean.length >= 2 && city.indexOf(clean.substring(0, 2)) >= 0) score = 60;

      if (score > 0) {
        results.push({ province: prov, city: city, longitude: CITY_DATA[prov][city], score: score });
      }
    }
  }

  // 按匹配度排序
  results.sort(function(a, b) { return b.score - a.score; });
  return results;
}

/**
 * 智能获取经度（支持自由输入）
 * 先精确匹配，失败则模糊搜索取最佳结果
 */
function smartGetLongitude(input) {
  if (!input) return null;

  // 尝试按"省市"格式解析
  var parts = input.split(/[,\s，、]/);
  var province = parts[0] ? parts[0].trim() : '';
  var city = parts[1] ? parts[1].trim() : '';

  // 精确匹配
  if (province && city) {
    var lon = getCityLongitude(province, city);
    if (lon !== null) return { longitude: lon, province: province, city: city, matched: 'exact' };
  }
  if (province && !city) {
    // 只传了一个词，先当省份试
    if (CITY_DATA[province]) {
      var firstCity = Object.keys(CITY_DATA[province])[0];
      return { longitude: CITY_DATA[province][firstCity], province: province, city: firstCity, matched: 'province' };
    }
    // 当城市名试
    city = province;
    province = '';
  }

  // 模糊搜索
  var results = searchCity(city || input);
  if (results.length > 0) {
    var best = results[0];
    return { longitude: best.longitude, province: best.province, city: best.city, matched: 'fuzzy', score: best.score };
  }

  return null;
}

