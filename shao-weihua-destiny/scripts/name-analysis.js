/**
 * 分析姓名五行补益
 * @param {string} name - 姓名
 * @param {string} dayWx - 日主五行（如"金"）
 * @param {string} yongshenWx - 用神五行
 * @returns {object} 姓名分析结果
 */
function analyzeName(name, dayWx, yongshenWx) {
  if (!name || !dayWx) return null;

  // 拆字
  var chars = name.split('');
  var charAnalysis = [];
  var wxCount = { '木': 0, '火': 0, '土': 0, '金': 0, '水': 0 };

  for (var ch of chars) {
    var wx = CHAR_WUXING[ch];
    if (!wx) {
      // 未收录的字，根据笔画数奇偶粗判阴阳，再按部首猜五行
      wx = guessWuxing(ch);
    }
    wxCount[wx] = (wxCount[wx] || 0) + 1;
    charAnalysis.push({
      char: ch,
      wuxing: wx,
      relation: getRelationToDayMaster(wx, dayWx)
    });
  }

  // 判断姓名整体对日主的补益
  var beneficial = 0;  // 补益分（同五行+生我）
  var harmful = 0;     // 克泄分（克我+我克+我生）
  for (var ca of charAnalysis) {
    if (ca.relation === '比劫' || ca.relation === '印星') beneficial++;
    if (ca.relation === '官杀' || ca.relation === '财星' || ca.relation === '食伤') harmful++;
  }

  // 判断对用神的补益
  var yongshenBenefit = 0;
  if (yongshenWx) {
    for (var ca2 of charAnalysis) {
      if (ca2.wuxing === yongshenWx) yongshenBenefit++;
      // 生用神者也算有利
      var SHENG = { '木': '火', '火': '土', '土': '金', '金': '水', '水': '木' };
      if (SHENG[ca2.wuxing] === yongshenWx) yongshenBenefit += 0.5;
    }
  }

  var verdict;
  var suggestion;
  if (beneficial >= harmful + 1) {
    verdict = '补益';
    suggestion = '姓名五行整体对日主有补益作用，名字起得不错。';
  } else if (harmful >= beneficial + 1) {
    verdict = '克泄';
    suggestion = '姓名五行对日主偏克泄，日常可通过穿戴幸运色、调整方位来弥补。';
  } else {
    verdict = '中性';
    suggestion = '姓名五行对日主影响偏中性，无明显补益也不算克泄。';
  }

  // 用神补益判断
  var yongshenVerdict = '';
  if (yongshenWx) {
    if (yongshenBenefit >= 1.5) {
      yongshenVerdict = '姓名中有字与用神（' + yongshenWx + '）同频，有助于开运。';
    } else if (yongshenBenefit >= 0.5) {
      yongshenVerdict = '姓名对用神（' + yongshenWx + '）有一定助力。';
    } else {
      yongshenVerdict = '姓名中缺少用神（' + yongshenWx + '）属性的字，日常多接触用神相关事物来弥补。';
    }
  }

  return {
    name: name,
    chars: charAnalysis,
    wxCount: wxCount,
    dayWx: dayWx,
    yongshenWx: yongshenWx,
    beneficial: beneficial,
    harmful: harmful,
    verdict: verdict,
    suggestion: suggestion,
    yongshenVerdict: yongshenVerdict,
    summary: '姓名"' + name + '"五行分布：' +
      Object.entries(wxCount).filter(function(e){return e[1]>0}).map(function(e){return e[0]+e[1]+'个'}).join('、') +
      '。' + suggestion + (yongshenVerdict ? yongshenVerdict : '')
  };
}

/**
 * 获取五行与日主的关系
 */
function getRelationToDayMaster(wx, dayWx) {
  if (wx === dayWx) return '比劫';
  var SHENG = { '木': '火', '火': '土', '土': '金', '金': '水', '水': '木' };
  var KE = { '木': '土', '土': '水', '水': '火', '火': '金', '金': '木' };
  if (SHENG[wx] === dayWx) return '印星';   // 生我者
  if (SHENG[dayWx] === wx) return '食伤';   // 我生者
  if (KE[wx] === dayWx) return '官杀';      // 克我者
  if (KE[dayWx] === wx) return '财星';      // 我克者
  return '未知';
}

